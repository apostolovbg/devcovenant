def _csv_to_list(raw_value: str) -> List[str]:
    """Expand a comma-separated metadata string into a clean list."""

    items = []
    for token in str(raw_value or "").split(","):
        cleaned = token.strip()
        if cleaned:
            items.append(cleaned)
    return items


def _resolved_role_file_selectors(
    *,
    raw_roles: str,
    raw_role_files: str,
) -> List[str]:
    """Resolve `resolved` role file selectors from merged metadata."""

    if raw_roles.strip():
        roles = dependency_license_sync.resolve_dependency_roles(
            _csv_to_list(raw_roles)
        )
    else:
        roles = list(dependency_license_sync.CANONICAL_DEPENDENCY_ROLES)
    pairs = dependency_license_sync.parse_role_selector_entries(
        entries=_csv_to_list(raw_role_files),
        allowed_roles=roles,
        metadata_key="dependency_role_files",
    )
    return [selector for role, selector in pairs if role == "resolved"]


def _descriptor_metadata_lists(
    repo_root: Path,
    policy_id: str,
) -> Tuple[List[str], Dict[str, List[str]]]:
    """Load descriptor defaults into order/list map representation."""

    descriptor = load_policy_descriptor(repo_root, policy_id)
    if descriptor is None:
        raise ValueError(f"Missing policy descriptor for `{policy_id}`.")
    order: List[str] = []
    values: Dict[str, List[str]] = {}
    for key, raw_value in descriptor.metadata.items():
        key_name = str(key).strip()
        if not key_name:
            continue
        order.append(key_name)
        values[key_name] = metadata_value_list(raw_value)
    return order, values


def _resolve_dependency_metadata(repo_root: Path) -> Dict[str, object]:
    """Resolve dependency-license-sync metadata from profiles and config."""

    order, values = _descriptor_metadata_lists(repo_root, POLICY_ID)
    descriptor = load_policy_descriptor(repo_root, POLICY_ID)
    context = build_metadata_context(repo_root)
    location = resolve_script_location(repo_root, POLICY_ID)
    custom_policy = bool(location and location.kind == "custom")
    _, resolved = resolve_policy_metadata_map(
        POLICY_ID,
        order,
        values,
        descriptor,
        context,
        custom_policy=custom_policy,
    )
    resolved_role_files = _resolved_role_file_selectors(
        raw_roles=str(resolved.get("dependency_roles", "")),
        raw_role_files=str(resolved.get("dependency_role_files", "")),
    )
    third_party_file = str(resolved.get("third_party_file", "")).strip()
    licenses_dir = str(resolved.get("licenses_dir", "")).strip()
    report_heading = str(resolved.get("report_heading", "")).strip()
    if not third_party_file:
        raise ValueError(
            "dependency-license-sync.metadata.third_party_file is missing."
        )
    if not licenses_dir:
        raise ValueError(
            "dependency-license-sync.metadata.licenses_dir is missing."
        )
    if not report_heading:
        raise ValueError(
            "dependency-license-sync.metadata.report_heading is missing."
        )
    return {
        "resolved_dependency_files": resolved_role_files,
        "third_party_file": third_party_file,
        "licenses_dir": licenses_dir,
        "report_heading": report_heading,
    }


def refresh_locks_and_licenses(
    repo_root: Path,
) -> Tuple[List[LockHandlerResult], List[Path]]:
    """Refresh selected lockfiles and policy-owned license artifacts."""

    metadata = _resolve_dependency_metadata(repo_root)
    dependency_files = set(metadata["resolved_dependency_files"])
    targets = [
        lock_name
        for lock_name in LOCKFILE_HANDLERS
        if lock_name in dependency_files
    ]
    results: List[LockHandlerResult] = []
    changed_lockfiles: List[str] = []
    for lock_name in targets:
        handler = LOCKFILE_HANDLERS[lock_name]
        result = handler(repo_root)
        results.append(result)
        if result.changed:
            changed_lockfiles.append(lock_name)

    modified_license_files = dependency_license_sync.refresh_license_artifacts(
        repo_root,
        changed_dependency_files=changed_lockfiles,
        third_party_file=str(metadata["third_party_file"]),
        licenses_dir=str(metadata["licenses_dir"]),
        report_heading=str(metadata["report_heading"]),
    )
    return results, modified_license_files
